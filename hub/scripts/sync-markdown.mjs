// 让 site/admin/markdown-core.js 与 luci-app-aurora-config 里的 Markdown 渲染器保持一致。
//
// 源头是 app 的 .dev/src/resource/utils/markdown.js:两条标记注释之间那段纯函数
// 被逐字取出,包成管理台能 import 的 ES module。app 那份是 LuCI 的 "require
// baseclass" 模块,浏览器无法直接 import,所以这里不是整文件复制。
//
// 需要同级目录里有 luci-app-aurora-config 的检出。改完源头后运行:
//   node scripts/sync-markdown.mjs
//
// 只检查不写入:
//   node scripts/sync-markdown.mjs --check

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const OPEN_MARKER = "// <markdown-core>";
const CLOSE_MARKER = "// </markdown-core>";
const SOURCE_LABEL = "luci-app-aurora-config/.dev/src/resource/utils/markdown.js";
const COPY_LABEL = "site/admin/markdown-core.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const hubRoot = path.resolve(here, "..");
const sourcePath = path.resolve(hubRoot, "..", "..", SOURCE_LABEL);
const copyPath = path.join(hubRoot, COPY_LABEL);

function fail(message) {
  console.error(message);
  process.exit(1);
}

if (!existsSync(sourcePath)) fail(`${SOURCE_LABEL} not found next to this repository (looked at ${sourcePath}).`);

const source = readFileSync(sourcePath, "utf8");
const start = source.indexOf(OPEN_MARKER);
const end = source.indexOf(CLOSE_MARKER);
if (start === -1 || end === -1 || end < start) {
  fail(`${SOURCE_LABEL} has no "${OPEN_MARKER}" … "${CLOSE_MARKER}" block.`);
}

const core = source.slice(start, end + CLOSE_MARKER.length);
const generated =
  `// Generated by scripts/sync-markdown.mjs — edit the source in ${SOURCE_LABEL}.\n` +
  `${core}\n\nexport { renderMarkdown, markdownToText };\n`;

if (process.argv.includes("--check")) {
  const existing = existsSync(copyPath) ? readFileSync(copyPath, "utf8") : "";
  if (existing !== generated) {
    fail(`${COPY_LABEL} is OUT OF SYNC with ${SOURCE_LABEL}.\nRun \`node scripts/sync-markdown.mjs\` to fix.`);
  }
  console.log(`${COPY_LABEL} matches ${SOURCE_LABEL}.`);
  process.exit(0);
}

writeFileSync(copyPath, generated);
console.log(`Synced ${SOURCE_LABEL} into ${COPY_LABEL}.`);
